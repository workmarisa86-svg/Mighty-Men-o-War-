let lang = 'en';
const listeners = [];
export function setLang(l) { lang = STR[l] ? l : 'en'; document.documentElement.lang = lang; listeners.forEach((f) => f(lang)); }
export function getLang() { return lang; }
export function onLang(f) { listeners.push(f); }
export function t(key, params) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll('{' + k + '}', params[k]);
  return s;
}
export function addStrings(en, es) { Object.assign(STR.en, en); Object.assign(STR.es, es); }

// Updates every element carrying data-i18n="key".
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}
